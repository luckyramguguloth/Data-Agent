from pptx import Presentation
from pptx.util import Inches, Pt
from pptx.dml.color import RGBColor
from pptx.enum.text import PP_ALIGN
from docx import Document
from docx.shared import Pt as DocxPt
from docx.shared import RGBColor as DocxColor
from docx.enum.text import WD_ALIGN_PARAGRAPH
import os

class ReportExporter:
    
    # --- POWERPOINT GENERATION ---
    def generate_pptx(self, filename, summary, queries, insights):
        """
        Creates a STYLED Professional Slide Deck.
        """
        prs = Presentation()

        # Helper to set dark background
        def set_dark_background(slide):
            background = slide.background
            fill = background.fill
            fill.solid()
            fill.fore_color.rgb = RGBColor(30, 30, 30) # Dark Grey

        # 1. TITLE SLIDE
        slide_layout = prs.slide_layouts[0] # Title Slide
        slide = prs.slides.add_slide(slide_layout)
        set_dark_background(slide)
        
        title = slide.shapes.title
        subtitle = slide.placeholders[1]
        
        title.text = f"Data Analysis Report\n{filename}"
        subtitle.text = "Generated by AI Data Analyst Agent"
        
        # Style Title
        title.text_frame.paragraphs[0].font.color.rgb = RGBColor(255, 255, 255)
        title.text_frame.paragraphs[0].font.bold = True
        subtitle.text_frame.paragraphs[0].font.color.rgb = RGBColor(200, 200, 200)

        # 2. EXECUTIVE SUMMARY
        slide_layout = prs.slide_layouts[1] # Title and Content
        slide = prs.slides.add_slide(slide_layout)
        set_dark_background(slide)
        
        title = slide.shapes.title
        title.text = "Executive Summary"
        title.text_frame.paragraphs[0].font.color.rgb = RGBColor(100, 149, 237) # Cornflower Blue
        
        content = slide.placeholders[1]
        content.text = summary
        for paragraph in content.text_frame.paragraphs:
            paragraph.font.color.rgb = RGBColor(255, 255, 255)
            paragraph.font.size = Pt(18)

        # 3. SQL INSIGHTS
        slide_layout = prs.slide_layouts[1]
        slide = prs.slides.add_slide(slide_layout)
        set_dark_background(slide)
        
        title = slide.shapes.title
        title.text = "Key SQL Queries & Insights"
        title.text_frame.paragraphs[0].font.color.rgb = RGBColor(100, 149, 237)
        
        tf = slide.placeholders[1].text_frame
        for q in queries:
            p = tf.add_paragraph()
            p.text = f"🔹 {q}"
            p.font.color.rgb = RGBColor(255, 255, 255)
            p.font.size = Pt(16)
            p.space_after = Pt(10)

        output_path = f"data/{filename}_report.pptx"
        prs.save(output_path)
        return output_path

    # --- WORD DOCUMENT GENERATION ---
    def generate_docx(self, filename, summary, queries, insights):
        """
        Creates a Professional Word Document Report.
        """
        doc = Document()
        
        # Title
        heading = doc.add_heading(f'Data Analysis Report: {filename}', 0)
        heading.alignment = WD_ALIGN_PARAGRAPH.CENTER
        
        # Subtitle
        p = doc.add_paragraph('Generated by AI Data Analyst Agent')
        p.alignment = WD_ALIGN_PARAGRAPH.CENTER
        doc.add_page_break()

        # Section 1: Executive Summary
        doc.add_heading('1. Executive Summary', level=1)
        p_summary = doc.add_paragraph(summary)
        p_summary.paragraph_format.space_after = DocxPt(12)

        # Section 2: Technical Queries
        doc.add_heading('2. Key SQL Queries', level=1)
        for q in queries:
            p = doc.add_paragraph(q, style='List Bullet')
        
        # Section 3: AI Insights (Placeholder for Deep Dive)
        doc.add_heading('3. AI Detected Patterns', level=1)
        doc.add_paragraph(insights if insights else "No deep dive insights recorded for this session.")

        output_path = f"data/{filename}_report.docx"
        doc.save(output_path)
        return output_path